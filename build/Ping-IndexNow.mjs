// Tell the search engines that read IndexNow that this site changed, instead of waiting to be
// discovered. Run by hand after a deploy, the way Make-Pages.mjs and Make-Icon.mjs are run by
// hand: nothing in CI runs this, and nothing needs it to build.
//
// Why it exists. Findra is days old, on a subdomain, with no inbound links, so the ordinary route
// to being crawled is somebody else linking to it - which has not happened and will not happen
// soon. IndexNow is the one channel that does not depend on that: a single POST naming the URLs
// that changed, honoured by Bing and Yandex. Bing is the one that matters here, because Copilot
// answers out of Bing's index, so this is the shortest path from "pushed" to "quotable".
//
// It is deliberately not automated on deploy. A submission is a claim that these pages really
// changed, and firing it on every push - including the ones that change a test - is how a site
// teaches an engine to stop believing its own signal.
//
//   node build/Ping-IndexNow.mjs            what it would send, and nothing else
//   node build/Ping-IndexNow.mjs --send     actually send it
//
// The key lives in exactly one place: the file the engines fetch to prove the submission came
// from somebody who can write to this host. There is no second copy of it in this script, because
// a key written down twice is a key that will one day be written down differently.

import { readFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC = join(ROOT, 'website', 'public');
const HOST = 'findra-search.netlify.app';

/// The key file is the source of truth. A bare 32-hex .txt at the root of the site whose contents
/// are its own name is the shape IndexNow specifies; finding it here rather than storing the key
/// in this file is what keeps the two from drifting.
const keyFile = readdirSync(PUBLIC).find((name) => /^[0-9a-f]{8,128}\.txt$/.test(name));
if (!keyFile) {
  throw new Error('no IndexNow key file in website/public - expected one named <key>.txt');
}

const key = keyFile.replace(/\.txt$/, '');
const stated = readFileSync(join(PUBLIC, keyFile), 'utf8').trim();
if (stated !== key) {
  throw new Error(`${keyFile} is named for ${key} and contains ${stated}; the engines fetch it and compare`);
}

// The sitemap is the list, rather than a second list kept here. It is generated by
// build/Make-Pages.mjs from the pages that actually exist, so it cannot name one that does not.
const sitemap = readFileSync(join(PUBLIC, 'sitemap.xml'), 'utf8');
const urlList = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]);
if (urlList.length === 0) {
  throw new Error('sitemap.xml lists no URLs');
}

// llms.txt is not in the sitemap on purpose - it is not a page - but it is the file an assistant
// reads first, and it changes when the pages do.
urlList.push(`https://${HOST}/llms.txt`);

const body = { host: HOST, key, keyLocation: `https://${HOST}/${keyFile}`, urlList };

console.log(`IndexNow, ${urlList.length} URLs, key ${key}`);
for (const url of urlList) console.log(`  ${url}`);

if (!process.argv.includes('--send')) {
  console.log('\nNothing sent. Re-run with --send once the deploy carrying these changes is live.');
  process.exit(0);
}

const response = await fetch('https://api.indexnow.org/IndexNow', {
  method: 'POST',
  headers: { 'Content-Type': 'application/json; charset=utf-8' },
  body: JSON.stringify(body),
});

// 200 is accepted, 202 is accepted-and-the-key-is-being-checked. Both are fine; anything else is
// worth reading, because a rejected submission is silent otherwise.
console.log(`\n${response.status} ${response.statusText}`);
if (response.status !== 200 && response.status !== 202) {
  console.log(await response.text());
  process.exit(1);
}
