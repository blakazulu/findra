using System.Globalization;
using System.Text.RegularExpressions;

using Findra;
using Findra.Diagnostics;
using Xunit;

/// <summary>
/// The README, asserted. Spec §9a makes four promises about it, and all four are the kind that
/// decay quietly: an image that was hand-edited once, a command that was renamed, a number pasted
/// from the wrong run, a comparison that felt fair at the time.
/// </summary>
public class ReadmeTests
{
    private static readonly string Readme = Repo.Read("README.md");

    [Fact]
    public void NoNamedCompetitorAppearsInTheReadme()
    {
        // Spec §9a: "No comparative claims against named competitors, because Findra cannot
        // benchmark them fairly and a claim it cannot defend is worse than no claim." The list is
        // on Repo because the winget listing has to obey the same rule, and it is deliberately
        // incomplete - see its comment. NoComparativeClaimIsMadeAgainstAnything below is what
        // catches the shape of the sentence rather than the name in it.
        foreach (string name in Repo.Competitors)
            Assert.DoesNotContain(name, Readme, StringComparison.OrdinalIgnoreCase);
    }

    [Fact]
    public void NoComparativeClaimIsMadeAgainstAnything()
    {
        // The shape rather than the name, which is what catches "faster than the built-in search"
        // and "unlike other tools". If a sentence genuinely needs one of these phrases, rewrite
        // the sentence: the honest version says what Findra does and how long it took here.
        foreach (string phrase in new[] { "faster than", "better than", "unlike other", "compared to" })
            Assert.DoesNotContain(phrase, Readme, StringComparison.OrdinalIgnoreCase);
    }

    [Fact]
    public void EveryImageTheReadmeShowsIsInTheRepository()
    {
        MatchCollection images = Regex.Matches(Readme, @"!\[[^\]]*\]\(([^)\s]+)\)");
        Assert.True(images.Count >= 4, $"the README shows {images.Count} images; spec §9a asks for the capsule, a result card, the first-run screen and settings");

        foreach (Match m in images)
        {
            string path = m.Groups[1].Value;
            Assert.True(Repo.Exists(path), $"the README shows '{path}', which is not in the repository");
        }
    }

    [Fact]
    public void EveryImageRecordsTheCommandThatProducedIt()
    {
        // Spec §9a: "A screenshot is regenerated by running a command, never hand-edited, and the
        // command that produced each one is recorded next to it in the repo so anyone can
        // reproduce it." Without the command beside it, an image is a mockup with a good alibi.
        string[] lines = Readme.Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n');
        for (int i = 0; i < lines.Length; i++)
        {
            if (!Regex.IsMatch(lines[i], @"!\[[^\]]*\]\([^)\s]+\)")) continue;
            string window = string.Join("\n", lines.Skip(Math.Max(0, i - 2)).Take(6));
            Assert.Contains("--searchshot", window, StringComparison.Ordinal);
        }
    }

    [Fact]
    public void EveryImageIsNamedByTheStateThatDrewIt()
    {
        // EveryImageRecordsTheCommandThatProducedIt only asks that the word `--searchshot` appear
        // within six lines of an image, which one command sitting between two images satisfies for
        // both, and which an alt text reading "--searchshot" satisfies on its own. This is the
        // half that ties a particular file to a particular render: the command beside the image
        // must name that exact file, and the state it names must be one --searchshot can draw.
        foreach (Match m in Regex.Matches(Readme, @"!\[[^\]]*\]\((docs/shots/[^)\s]+)\)"))
        {
            string path = m.Groups[1].Value;
            Match cmd = Regex.Match(
                Readme,
                @"--searchshot\s+" + Regex.Escape(path) + @"\s+([a-z]+)(?:\s+([A-Za-z]+))?");
            Assert.True(cmd.Success, $"no `--searchshot {path} <state>` line in the README produces '{path}'");
            Assert.Contains(cmd.Groups[1].Value, SearchShot.States);
            if (cmd.Groups[2].Success)
                Assert.Contains(cmd.Groups[2].Value, Palette.BuiltIn.Select(p => p.Name));
        }
    }

    [Fact]
    public void EveryCommandTheReadmeTellsYouToRunIsOneFindraActuallyHas()
    {
        // Spec §9a: "No claim appears in the README that a reader cannot reproduce with a command
        // from the README itself." A renamed mode makes every instruction around it false, and the
        // person who finds out is a stranger following the page.
        string program = Repo.Read("src/Findra/Program.cs");
        var known = new HashSet<string>(
            Regex.Matches(program, @"""(--[a-z]+)""\s*=>").Select(m => m.Groups[1].Value),
            StringComparer.Ordinal);

        Assert.NotEmpty(known);
        foreach (Match m in Regex.Matches(Readme, @"findra(?:\.exe)?\s+(--[a-z-]+)"))
            Assert.Contains(m.Groups[1].Value, known);
    }

    [Fact]
    public void EveryModeFindraHasIsOneTheReadmeTellsYouAbout()
    {
        // The other direction, and the one that decays: a mode added after this page was written
        // is a thing the product can do that its only public page does not mention. The three
        // internal modes are excluded by name rather than by pattern, because "internal" is a
        // judgement and the list is where that judgement is recorded.
        string program = Repo.Read("src/Findra/Program.cs");
        string[] internalModes = ["--names", "--index", "--stop"];

        foreach (Match m in Regex.Matches(program, @"""(--[a-z]+)""\s*=>"))
        {
            string mode = m.Groups[1].Value;
            if (internalModes.Contains(mode)) continue;
            Assert.Contains("findra " + mode, Readme, StringComparison.Ordinal);
        }
    }

    [Fact]
    public void EveryFileTheReadmePointsAtIsInTheRepository()
    {
        // EveryImageTheReadmeShowsIsInTheRepository covers the images and nothing else, and the
        // page points at eight more things - the licence, the NOTICE the attribution lives in,
        // the font licence, the installer script, the manifests, the signing policy. A renamed or
        // moved file leaves a dead reference on the one page a stranger reads first, and no other
        // test in the tree would notice.
        var referenced = new SortedSet<string>(StringComparer.Ordinal);

        // Repo-relative paths, anchored on the top-level directories that actually exist, so that
        // `github.com/blakazulu/findra` and `%LOCALAPPDATA%\Findra\index` are not mistaken for one.
        foreach (Match m in Regex.Matches(Readme,
                     @"(?<![\w./-])((?:docs|src|tests|assets|installer|packaging|build)/[A-Za-z0-9_./-]*[A-Za-z0-9_-])"))
            referenced.Add(m.Groups[1].Value);

        // Markdown links to somewhere in the repository rather than out on the web.
        foreach (Match m in Regex.Matches(Readme, @"\]\(([^)\s#][^)\s]*)\)"))
            if (!m.Groups[1].Value.StartsWith("http", StringComparison.OrdinalIgnoreCase))
                referenced.Add(m.Groups[1].Value);

        // The two the licence section names, which carry no directory and no extension.
        foreach (string bare in new[] { "LICENSE", "NOTICE" })
            if (Readme.Contains('`' + bare + '`', StringComparison.Ordinal)) referenced.Add(bare);

        Assert.True(referenced.Count >= 10, $"the README points at only {referenced.Count} files in the repository; the licence, the NOTICE, the font licence, the installer and the manifests are all supposed to be among them");

        foreach (string path in referenced)
        {
            string full = Repo.Path_(path.TrimEnd('/'));
            Assert.True(File.Exists(full) || Directory.Exists(full),
                        $"the README points at '{path}', which is not in the repository");
        }
    }

    [Fact]
    public void TheCountsTheReadmeQuotesAreTheCountsTheCodeHas()
    {
        // Two numbers on the page are typed rather than measured: how many surfaces --searchshot
        // can draw and how many palettes ship. Both are the kind a reader checks in ten seconds by
        // running the command, which is the whole promise of the page, and both move when somebody
        // adds a state or a palette without thinking about the README.
        Assert.Contains($"draws {Word(SearchShot.States.Count)} surfaces", Readme, StringComparison.OrdinalIgnoreCase);
        Assert.Contains($"{Word(Palette.BuiltIn.Count)} palettes ship", Readme, StringComparison.OrdinalIgnoreCase);
    }

    [Fact]
    public void TheReadmeSendsAReaderToTheSameSiteTheSiteSaysItIs()
    {
        // A stranger who lands on the repository was given no route to the page written to
        // explain the product, and a stranger on the page who clicked through to GitHub found a
        // file behaving as though the site did not exist. The link is one sentence; the reason it
        // is a test is that a URL typed into prose has no way of noticing when the site moves.
        //
        // Held against the site's OWN canonical link rather than against a constant repeated
        // here, because a third copy of the address is a third thing to keep in step. Netlify
        // publishes website/public exactly as it sits, so that tag is what the page really is.
        Match canonical = Regex.Match(
            Repo.Read("website/public/index.html"),
            @"<link\s+rel=""canonical""\s+href=""(?<url>https://[^""]+)""");
        Assert.True(canonical.Success, "the site page declares no canonical URL to check the README against");

        string site = canonical.Groups["url"].Value.TrimEnd('/');
        Assert.Contains(site, Readme, StringComparison.Ordinal);
    }

    /// <summary>A small number in words, because the README is prose. Deliberately narrow: a count
    /// outside this range means the page needs rewriting rather than a bigger lookup table.</summary>
    private static string Word(int n) => n switch
    {
        4 => "four", 5 => "five", 6 => "six", 7 => "seven", 8 => "eight", 9 => "nine", 10 => "ten",
        11 => "eleven", 12 => "twelve", 13 => "thirteen", 14 => "fourteen", 15 => "fifteen",
        16 => "sixteen", 17 => "seventeen", 18 => "eighteen", 19 => "nineteen", 20 => "twenty",
        21 => "twenty-one", 22 => "twenty-two", 23 => "twenty-three", 24 => "twenty-four",
        _ => throw new InvalidOperationException($"{n} is outside the range the README's prose was written for"),
    };

    [Fact]
    public void TheReadmeCarriesAMeasuredBenchmarkAndTheMachineItWasMeasuredOn()
    {
        // "Numbers without the machine beside them are marketing, not measurement, so the machine
        // line is not optional" (spec §9).
        Assert.Contains("## Findra benchmark", Readme, StringComparison.Ordinal);
        Assert.Contains("### Machine", Readme, StringComparison.Ordinal);
        Assert.Contains("| CPU |", Readme, StringComparison.Ordinal);
        Assert.Contains("| RAM |", Readme, StringComparison.Ordinal);
        Assert.Contains("| Windows |", Readme, StringComparison.Ordinal);
        Assert.Contains("### Name query latency", Readme, StringComparison.Ordinal);
    }

    [Fact]
    public void TheBenchmarkFragmentIsTheWholeOneAndNotTheFlatteringHalfOfIt()
    {
        // Every heading Bench.Fragment writes, in the order it writes them. The fragment is
        // quoted verbatim precisely so that the sections nobody would choose - a store that is
        // larger than expected, a query with a bad p95 - travel with the ones anybody would.
        // Picking two headings out of six is how a measurement becomes a selection.
        string[] sections =
            ["## Findra benchmark", "### Machine", "### Volumes", "### Name query latency",
             "### Full-text query latency", "### Document extraction", "### Stores"];

        int at = -1;
        foreach (string section in sections)
        {
            int next = Readme.IndexOf(section, at + 1, StringComparison.Ordinal);
            Assert.True(next > at, $"the benchmark fragment is missing '{section}', or it is out of order");
            at = next;
        }
    }

    [Fact]
    public void TheThroughputFigureCameFromARunLargeEnoughToReproduce()
    {
        // The default corpus clears the one-second floor and still disagrees with itself by more
        // than the number deserves - the fragment's own comment says two runs came back sixteen
        // percent apart at a fifth of a second, and a second and a bit is not far enough from
        // that. Pasting `findra --searchbench out.md` output verbatim puts 2,500 here and fails.
        Match m = Regex.Match(Readme, @"Corpus for the extraction row:\s*([\d,]+)\s+generated \.txt");
        Assert.True(m.Success, "the README's benchmark fragment carries no corpus note");

        int files = int.Parse(m.Groups[1].Value.Replace(",", "", StringComparison.Ordinal), CultureInfo.InvariantCulture);
        Assert.True(files >= 10_000,
            $"the extraction row was measured over {files} files; regenerate with " +
            "`findra --searchbench readme-bench.md 10000` before quoting a rate");
    }

    [Fact]
    public void TheModelTotalIsTheMeasuredOneAndNotTheConservativeFloor()
    {
        // Spec §6: the declared minimum-byte floors are conservative by a wide margin, and the
        // README's number is the measured total. Reading it from the same constant every other
        // surface reads means it cannot drift into being typed by hand.
        Assert.Contains(Sizes.Human(Capabilities.TotalBytes(Capabilities.All)), Readme, StringComparison.Ordinal);
    }

    [Fact]
    public void TheAttributionTheNoticeRequiresIsAboveTheFold()
    {
        // Spec §11: Apache-2.0 was chosen over MIT because it carries a PROPAGATING attribution
        // requirement, and "the README states the same in plain language above the fold". A
        // licence line at the very bottom is the thing MIT would have given anyway.
        //
        // Asserted on ONE PARAGRAPH rather than on the first three thousand characters, because
        // the first draft did the latter and was green against a page whose attribution paragraph
        // had been gutted: `git clone https://github.com/blakazulu/findra` sits at character 2,848
        // and carries both the name and the URL on its own. The requirement is that the page says
        // what you must keep and why, in one place, early - which is four things in one paragraph
        // and not two tokens anywhere in the opening.
        string top = Readme.Length > 3000 ? Readme[..3000] : Readme;
        string[] paragraphs = top.Replace("\r\n", "\n", StringComparison.Ordinal).Split("\n\n");
        string[] required = ["Apache-2.0", "NOTICE", "blakazulu", "github.com/blakazulu/findra"];

        Assert.True(
            paragraphs.Any(p => required.All(r => p.Contains(r, StringComparison.OrdinalIgnoreCase))),
            "no paragraph above the fold states the licence, the NOTICE file, blakazulu and the " +
            "project URL together; spec §11 asks for the propagating attribution in plain language, " +
            "not for the name and the URL to turn up somewhere in the opening");
    }

    [Fact]
    public void TheOneRequestThatLeavesTheMachineIsStillWrittenDownHere()
    {
